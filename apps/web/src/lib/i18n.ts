export function resolveLanguage(language: Language, systemLanguage = "en-US"): ResolvedLanguage {
  if (language === "de") return "de";
  if (language === "en") return "en";
  return systemLanguage.toLowerCase().startsWith("de") ? "de" : "en";
}

export function localeFor(language: ResolvedLanguage): string {
  return language === "de" ? "de-DE" : "en-US";
}

export type PluralCategory = "zero" | "one" | "two" | "few" | "many" | "other";

export function pluralCategory(count: number, language: ResolvedLanguage): PluralCategory {
  if (language === "de") {
    return count === 1 ? "one" : "other";
  }
  if (count === 0) return "other";
  return count === 1 ? "one" : "other";
}

export function translate(
  language: ResolvedLanguage,
  key: MessageKey | string,
  values: Record<string, string | number> = {},
): string {
  const count = typeof values.count === "number" ? values.count : undefined;
  let resolvedKey: string = key;
  if (count !== undefined) {
    const cat = pluralCategory(count, language);
    const pluralKey = `${key}_${cat}`;
    const langCatalog = messages[language] as Record<string, MessageValue>;
    const enCatalog = messages.en as Record<string, MessageValue>;
    if (pluralKey in langCatalog || pluralKey in enCatalog) {
      resolvedKey = pluralKey;
    }
  }
  const langCatalog = messages[language] as Record<string, MessageValue>;
  const enCatalog = messages.en as Record<string, MessageValue>;
  const value =
    langCatalog[resolvedKey] ?? enCatalog[resolvedKey] ?? langCatalog[key] ?? enCatalog[key];
  if (value === undefined) return String(key);
  if (typeof value === "function") return value(values);
  return value.replace(/\{(\w+)\}/g, (_match: string, name: string) =>
    String(values[name] ?? `{${name}}`),
  );
}

export function messageKeys(): MessageKey[] {
  return Object.keys(messages.en) as MessageKey[];
}

